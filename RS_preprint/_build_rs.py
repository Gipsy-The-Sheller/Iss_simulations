# -*- coding: utf-8 -*-
"""Build the Research Square preprint version of the manuscript.

Reads ../manuscript.tex and writes ./manuscript.tex plus _abstract.txt,
applying only what the preprint needs:

  * drafting comments dropped -- the file header, the section rules and the
    "NOTE (do not reintroduce)" block.  They are all full-line comments; the
    source has no trailing comments, and every `%` inside a line is an
    escaped `\%`.
  * \\graphicspath{{../}} added, so the body keeps its `figures/...` paths
    while the images stay in the repository root.  Research Square takes a
    PDF only, so this folder is a build folder, not a self-contained
    submission package like MPE_sumb/.
  * the bibliography points at ../refs/ for the same reason.
  * corresponding-author e-mail in the author block.
  * one sentence at the top of the abstract saying what is new here.  The
    Research Square policy admits "research articles with complete methods
    and results sections" but not "commentaries" (1.2), and a critique of a
    published method is exactly the shape a screening editor may mis-file.
    The sentence names the new theory, the new simulations and the
    re-analyses, so the genre is explicit in the first two lines of the
    abstract.  The title is left alone: it is the paper's citation identity
    and has to stay the same as the MPE submission's.
  * an AI-use disclosure at the end of Material and methods, required by the
    Research Square editorial policy, section 1.3 ("Use of an LLM should be
    properly documented in the Methods section").
  * CRediT / competing interest / funding declarations, wording shared with
    MPE_sumb/_build_mpe.py so the two versions cannot drift apart.
  * _abstract.txt: the abstract as plain text, for pasting into the
    submission form.  Whatever is typed into that form is posted verbatim,
    so it has to match the PDF.

Nothing else changes: no spelling conversion, no section reordering, no
line-number removal.  _verify.py checks that claim.

Build:  pdflatex manuscript && bibtex manuscript && pdflatex manuscript x2
"""
import io
import re
import sys

SRC = '../manuscript.tex'
OUT = 'manuscript.tex'
ABSTRACT_OUT = '_abstract.txt'

EMAIL = 'zjxmolls@outlook.com'
EMAIL_CLAUSE = '\\\\\n        Correspondence: ' + EMAIL

AUTHOR_OLD = ('\\thanks{College of Biological Science \\& Medical Engineering,\n'
              '        Donghua University, Shanghai 201620, China.}')
AUTHOR_NEW = AUTHOR_OLD[:-1] + EMAIL_CLAUSE + '}'

# The new-work sentence and the abstract sentence it follows.  Both the LaTeX
# and the paste-into-the-form path use them, so the two cannot disagree.
ABSTRACT_ANCHOR = 'retains phylogenetic signal.'
POSITIONING_TEX = ('We characterize the index exactly, and test that\n'
                   'characterization in new simulations and in re-analyses of two published\n'
                   'data sets.')
POSITIONING = re.sub(r'\s+', ' ', POSITIONING_TEX)

HEADER = r"""%% =====================================================================
%%  Research Square preprint --- generated by _build_rs.py from
%%  ../manuscript.tex; see README.md.  Body text is unchanged except for
%%  the additions listed there.
%%  Build:  pdflatex manuscript && bibtex manuscript && pdflatex manuscript x2
%% =====================================================================
"""

GRAPHICSPATH = r"""%% figures/ and refs/ live in the repository root: this folder is where the
%% PDF is built and uploaded, not a self-contained submission package.
\graphicspath{{../}}"""

AI_DISCLOSURE = r"""\subsection*{Use of AI-assisted tools}
\addcontentsline{toc}{subsection}{Use of AI-assisted tools}

Claude Code (Anthropic), an AI coding assistant, was used in the preparation
of this work. It assisted in drafting and editing the manuscript text, and in
deriving and checking the mathematical results reported here. All content was
reviewed by the author, who takes full responsibility for the work and for its
conclusions; the tool is not an author and cannot take responsibility for it.
"""

DECLARATIONS = r"""\section*{CRediT authorship contribution statement}
\addcontentsline{toc}{section}{CRediT authorship contribution statement}

\textbf{Zhi-Jie Xu:} Conceptualization, Methodology, Software, Formal
analysis, Investigation, Writing -- original draft, Writing -- review and
editing, Visualization.

\section*{Declaration of competing interest}
\addcontentsline{toc}{section}{Declaration of competing interest}

The author declares that he has no known competing financial interests or
personal relationships that could have appeared to influence the work reported
in this paper.

\section*{Funding}
\addcontentsline{toc}{section}{Funding}

This research did not receive any specific grant from funding agencies in the
public, commercial, or not-for-profit sectors.
"""

# --------------------------------------------------------------- plain text
# The abstract has to survive being pasted into a web form.  Each entry is an
# exact snippet of the source abstract; anything unmapped is caught by the
# [$\\{}] check below rather than shipped as raw LaTeX.
PLAIN = [
    (r'\noindent', ' '),
    (r'\citep{xia2003iss}', '(Xia et al. 2003)'),
    (r'$\Iss=\Hbar/\HFSS$', 'Iss = Hbar/HFSS'),
    (r'$\E[\Iss]$', 'E[Iss]'),
    (r'$\langle e^{\mu d}\rangle$', '<e^(mu d)>'),
    (r'$\lambda$', 'lambda'),
    (r'$p$', 'p'),
    (r'$1.2\%$', '1.2%'),
    ('---', '--'),
]


def strip_comments(t):
    """Drop full-line comments.  Trailing ones would need \\% care; there are
    none in the source, and _verify.py would flag one if it appeared."""
    return re.sub(r'(?m)^[ \t]*%[^\n]*\n?', '', t)


def sub_once(t, pattern, repl, what):
    out, n = re.subn(pattern, lambda m: repl, t, count=1)
    if n != 1:
        raise SystemExit('%s not found exactly once in %s -- check manuscript.tex'
                         % (what, SRC))
    return out


def build(src):
    doc = strip_comments(src)

    doc = sub_once(doc, re.escape(ABSTRACT_ANCHOR),
                   ABSTRACT_ANCHOR + ' ' + POSITIONING_TEX, 'abstract opening')

    anchor = '\\usepackage[hidelinks]{hyperref}'
    if doc.count(anchor) != 1:
        raise SystemExit('hyperref line not found exactly once -- check %s' % SRC)
    doc = doc.replace(anchor, anchor + '\n\n' + GRAPHICSPATH)

    doc = sub_once(doc, r'\\bibliography\{refs/refs_iss_clean\}',
                   '\\bibliography{../refs/refs_iss_clean}', 'bibliography path')

    doc = sub_once(
        doc,
        r'\\thanks\{College of Biological Science \\& Medical Engineering,\s*'
        r'Donghua University, Shanghai 201620, China\.\}',
        AUTHOR_NEW,
        'author block')

    doc = sub_once(doc, r'\\section\*\{Data availability\}',
                   AI_DISCLOSURE + '\n\\section*{Data availability}',
                   'Data availability heading')

    doc = sub_once(doc, r'\\bibliographystyle\{plainnat\}',
                   DECLARATIONS + '\n\\bibliographystyle{plainnat}',
                   'bibliographystyle')

    doc = re.sub(r'\n{4,}', '\n\n\n', doc)
    return HEADER + doc


def abstract_text(src):
    m = re.search(r'\\begin\{abstract\}(.*?)\\end\{abstract\}', src, re.S)
    if not m:
        raise SystemExit('abstract environment not found -- check %s' % SRC)
    t = m.group(1)
    for a, b in PLAIN:
        t = t.replace(a, b)
    if t.count(ABSTRACT_ANCHOR) != 1:
        raise SystemExit('abstract anchor %r not found exactly once -- check %s'
                         % (ABSTRACT_ANCHOR, SRC))
    t = t.replace(ABSTRACT_ANCHOR, ABSTRACT_ANCHOR + ' ' + POSITIONING)
    left = sorted(set(re.findall(r'[$\\{}]', t)))
    if left:
        raise SystemExit('unmapped LaTeX left in the abstract: %s -- add it to PLAIN'
                         % ' '.join(left))
    paras = [re.sub(r'[ \t\n]+', ' ', p).strip() for p in re.split(r'\n\s*\n', t)]
    return '\n\n'.join(p for p in paras if p)


def main():
    src = io.open(SRC, encoding='utf-8').read()
    doc = build(src)
    ab = abstract_text(src)
    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(doc)
    io.open(ABSTRACT_OUT, 'w', encoding='utf-8', newline='\n').write(ab + '\n')
    print('wrote %s (%d lines)' % (OUT, doc.count('\n')))
    print('wrote %s (%d words, %d paragraphs) -- Research Square states no limit'
          % (ABSTRACT_OUT, len(ab.split()), ab.count('\n\n') + 1))


if __name__ == '__main__':
    main()
